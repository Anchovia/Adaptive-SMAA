"""Generate the derived files of the Iris shader pack from this repository's SMAA sources.

  shaders/lib/SMAA.glsl        Projects/CMAA2/SMAA/SMAA.hlsl (blob af2383aa, minimal branch 60bae94) with
                               LF line endings, two non-ASCII diagram characters replaced by '.', a '.'
                               after the five banner comment lines that end in a backslash, and an
                               optional SMAA_ADAPTIVE_TIERS_AT_MAX switch (every tier searches the preset
                               maximum, so Adaptive output must equal Original). Nothing else changes.
  shaders/textures/AreaTex.png    160x560, R = byte 0, G = byte 1 of AreaTex.h (B 0, A 255)
  shaders/textures/SearchTex.png  64x16, R = SearchTex.h byte (G, B 0, A 255)
  *.png.mcmeta                 AreaTex bilinear + clamp, SearchTex nearest + clamp (the demo samples
                               searchTex only at texel centres, so nearest returns the same values)

Image row 0 is the first row of the header data, the same memory order the demo uploads to D3D11.

usage: python make_iris_assets.py <repo root> <pack dir> [--text-only]
"""
import hashlib
import re
import struct
import sys
import zlib
from pathlib import Path

SMAA_HLSL_BLOB = 'af2383aa7e0a365f73bb8d11496533527bc8066d'

HEADER = b"""// Iris shader pack copy of Projects/CMAA2/SMAA/SMAA.hlsl (git blob af2383aa, branch
// tooling/adaptive-selected-cross5-minimal 60bae94), generated by Tools/Iris/make_iris_assets.py.
// Changes: LF line endings, two non-ASCII diagram characters replaced by '.', a '.' after the five banner
// comment lines that end in a backslash (GLSL 3.30 has no line continuation), and the optional
// SMAA_ADAPTIVE_TIERS_AT_MAX switch below the Adaptive tier block. Compiled with SMAA_GLSL_3.

"""


def git_blob_sha1(data):
    return hashlib.sha1(b'blob %d\0' % len(data) + data).hexdigest()


def replace_once(text, old, new, label):
    if text.count(old) != 1:
        raise SystemExit(f'{label}: expected one match, found {text.count(old)}')
    return text.replace(old, new)


def make_glsl(src):
    # The repository stores LF; a core.autocrlf checkout has CRLF in the working tree.
    text = src.replace(b'\r\n', b'\n')
    if git_blob_sha1(text) != SMAA_HLSL_BLOB:
        raise SystemExit('SMAA.hlsl is not the expected blob')
    text = text.replace(b'\xb7', b'.')
    if any(b > 127 for b in text):
        raise SystemExit('non-ASCII bytes left')
    # Five lines of the ASCII-art banner comment end in a backslash, which GLSL 3.30 compilers
    # (glslang) read as an unsupported line continuation even inside a comment.
    lines = text.split(b'\n')
    ending = [i for i, line in enumerate(lines) if line.endswith(b'\\')]
    if len(ending) != 5 or not all(lines[i].startswith(b' *') and i < 40 for i in ending):
        raise SystemExit(f'unexpected backslash line endings at {ending}')
    for i in ending:
        lines[i] += b'.'
    text = b'\n'.join(lines)
    text = replace_once(text, b"""#error Adaptive SMAA needs one of the four presets
#endif
#undef SMAA_MAX_SEARCH_STEPS
#define SMAA_MAX_SEARCH_STEPS SMAA_ADAPTIVE_STEPS2
#endif
""", b"""#error Adaptive SMAA needs one of the four presets
#endif
#if defined(SMAA_ADAPTIVE_TIERS_AT_MAX)
// Test switch (Iris pack): every tier searches the preset maximum, so the output must equal Original.
#undef SMAA_ADAPTIVE_STEPS0
#undef SMAA_ADAPTIVE_STEPS1
#undef SMAA_ADAPTIVE_STEPS2
#define SMAA_ADAPTIVE_STEPS0 SMAA_MAX_SEARCH_STEPS
#define SMAA_ADAPTIVE_STEPS1 SMAA_MAX_SEARCH_STEPS
#define SMAA_ADAPTIVE_STEPS2 SMAA_MAX_SEARCH_STEPS
#else
#undef SMAA_MAX_SEARCH_STEPS
#define SMAA_MAX_SEARCH_STEPS SMAA_ADAPTIVE_STEPS2
#endif
#endif
""", 'tiers-at-max')
    return HEADER + text


def header_bytes(path, name):
    text = path.read_text(encoding='latin-1')
    body = text[text.index(name):]
    body = body[body.index('{') + 1:body.index('}')]
    return bytes(int(v, 16) for v in re.findall(r'0x([0-9a-fA-F]{2})', body))


def png(width, height, rgba_rows):
    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data) & 0xffffffff)
    raw = b''.join(b'\0' + row for row in rgba_rows)
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def main():
    repo, pack = Path(sys.argv[1]), Path(sys.argv[2])
    text_only = '--text-only' in sys.argv
    smaa = repo / 'Projects/CMAA2/SMAA'
    out = pack / 'shaders'
    (out / 'lib').mkdir(parents=True, exist_ok=True)
    glsl = make_glsl((smaa / 'SMAA.hlsl').read_bytes())
    (out / 'lib/SMAA.glsl').write_bytes(glsl)
    print('lib/SMAA.glsl', len(glsl), hashlib.sha256(glsl).hexdigest())
    if text_only:
        return
    area = header_bytes(smaa / 'AreaTex.h', 'areaTexBytes')
    search = header_bytes(smaa / 'SearchTex.h', 'searchTexBytes')
    if len(area) != 160 * 560 * 2 or len(search) != 64 * 16:
        raise SystemExit(f'unexpected texture sizes {len(area)} {len(search)}')
    area_rows = [b''.join(bytes((area[(y * 160 + x) * 2], area[(y * 160 + x) * 2 + 1], 0, 255)) for x in range(160)) for y in range(560)]
    search_rows = [b''.join(bytes((search[y * 64 + x], 0, 0, 255)) for x in range(64)) for y in range(16)]
    (out / 'textures').mkdir(exist_ok=True)
    files = {
        'textures/AreaTex.png': png(160, 560, area_rows),
        'textures/SearchTex.png': png(64, 16, search_rows),
        'textures/AreaTex.png.mcmeta': b'{"texture": {"blur": true, "clamp": true}}\n',
        'textures/SearchTex.png.mcmeta': b'{"texture": {"blur": false, "clamp": true}}\n',
    }
    for name, data in files.items():
        (out / name).write_bytes(data)
        print(name, len(data), hashlib.sha256(data).hexdigest())
    print('AreaTex.h bytes', hashlib.sha256(area).hexdigest(), 'SearchTex.h bytes', hashlib.sha256(search).hexdigest())


if __name__ == '__main__':
    main()
