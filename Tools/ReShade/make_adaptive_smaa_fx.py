"""Build AdaptiveSMAA.fx / AdaptiveSMAA.fxh from SweetFX SMAA.fx / SMAA.fxh (CeeJayDK/SweetFX 93ddf39).

Every change is an exact text replacement that must match once, so the output is the SweetFX source plus
the Adaptive tier changes of tooling/adaptive-tier-minimal (644f836) and nothing else:
  - per-preset 1% tiers (T1, T2, three orthogonal search lengths; the top tier replaces the preset maximum)
  - the edge pass stores the tier (0 / 0.5 / 1) in the third channel of an RGBA8 edge texture
  - the blending weight pass picks the search length from that tier
  - the top tier ends its searches at offset[2] like the original; shorter tiers end inside their last step
  - ADAPTIVE_SMAA_TIERS_AT_PRESET_MAX=1 makes every tier search the preset maximum (equivalence test with SMAA.fx)
The ReShade wrapper keeps SMAA.fx's passes, samplers and stencil use; textures get unique names and the
custom-uniform preset is removed because the tiers exist only for the four fixed presets.

usage: python -I make_adaptive_smaa_fx.py <SweetFX checkout> <output dir>
"""
import hashlib
import sys
from pathlib import Path

SOURCE_SHA256 = {
    'Shaders/SweetFX/SMAA.fx': 'fd6591eeb70ff584ac4d774ed3c79af5efac34f5de1a36f8f873e959259c0007',
    'Shaders/SweetFX/SMAA.fxh': 'ee18b0f376585338cdb477a0900757cebac86d3c476ef99955348b55818c8310',
}

ORIGIN = """ * AdaptiveSMAA: derived from SweetFX SMAA{ext} (github.com/CeeJayDK/SweetFX, commit 93ddf39,
 * SHA-256 {sha}).
 * The changes add the Adaptive SMAA contrast tiers of the research branch tooling/adaptive-tier-minimal
 * (644f836) and are generated by Tools/ReShade/make_adaptive_smaa_fx.py. Not an official SMAA or
 * SweetFX release.
"""


def replace_once(text, old, new, label):
    count = text.count(old)
    if count != 1:
        raise SystemExit(f'{label}: expected one match, found {count}')
    return text.replace(old, new)


def build_fxh(src, sha):
    out = replace_once(src, '/**\n * Copyright (C) 2013 Jorge Jimenez',
                       '/**\n' + ORIGIN.format(ext='.fxh', sha=sha) + ' *\n * Copyright (C) 2013 Jorge Jimenez', 'origin')

    out = replace_once(out, """#elif defined(SMAA_PRESET_ULTRA)
#define SMAA_THRESHOLD 0.05
#define SMAA_MAX_SEARCH_STEPS 32
#define SMAA_MAX_SEARCH_STEPS_DIAG 16
#define SMAA_CORNER_ROUNDING 25
#endif
""", """#elif defined(SMAA_PRESET_ULTRA)
#define SMAA_THRESHOLD 0.05
#define SMAA_MAX_SEARCH_STEPS 32
#define SMAA_MAX_SEARCH_STEPS_DIAG 16
#define SMAA_CORNER_ROUNDING 25
#endif

/**
 * Adaptive SMAA: the edge pass stores a contrast tier of finalDelta (below SMAA_ADAPTIVE_T1: 0,
 * below SMAA_ADAPTIVE_T2: 0.5, else 1) in the third channel of an RGBA8 edge texture, and the
 * blending weight pass searches SMAA_ADAPTIVE_STEPS0, SMAA_ADAPTIVE_STEPS1 or SMAA_MAX_SEARCH_STEPS
 * orthogonal steps by that tier. Per preset, every finalDelta band changed at most 1% of its edges
 * by more than 8/255 against the preset's Original in the CMAA2 demo measurements. The top tier
 * replaces the preset's orthogonal maximum; diagonal searches keep the preset length.
 * ADAPTIVE_SMAA_TIERS_AT_PRESET_MAX=1 keeps the preset maximum for every tier (output equals SMAA.fx).
 */
#if defined(SMAA_PRESET_LOW)
#define SMAA_ADAPTIVE_T1 (51.5 / 255.0)
#define SMAA_ADAPTIVE_T2 (63.5 / 255.0)
#define SMAA_ADAPTIVE_STEPS0 2
#define SMAA_ADAPTIVE_STEPS1 3
#define SMAA_ADAPTIVE_STEPS2 4
#elif defined(SMAA_PRESET_MEDIUM)
#define SMAA_ADAPTIVE_T1 (38.5 / 255.0)
#define SMAA_ADAPTIVE_T2 (76.5 / 255.0)
#define SMAA_ADAPTIVE_STEPS0 3
#define SMAA_ADAPTIVE_STEPS1 6
#define SMAA_ADAPTIVE_STEPS2 8
#elif defined(SMAA_PRESET_HIGH)
#define SMAA_ADAPTIVE_T1 (31.5 / 255.0)
#define SMAA_ADAPTIVE_T2 (51.5 / 255.0)
#define SMAA_ADAPTIVE_STEPS0 2
#define SMAA_ADAPTIVE_STEPS1 6
#define SMAA_ADAPTIVE_STEPS2 12
#elif defined(SMAA_PRESET_ULTRA)
#define SMAA_ADAPTIVE_T1 (19.5 / 255.0)
#define SMAA_ADAPTIVE_T2 (51.5 / 255.0)
#define SMAA_ADAPTIVE_STEPS0 3
#define SMAA_ADAPTIVE_STEPS1 8
#define SMAA_ADAPTIVE_STEPS2 20
#else
#error Adaptive SMAA needs one of the four presets
#endif
#if ADAPTIVE_SMAA_TIERS_AT_PRESET_MAX
#undef SMAA_ADAPTIVE_STEPS0
#undef SMAA_ADAPTIVE_STEPS1
#undef SMAA_ADAPTIVE_STEPS2
#define SMAA_ADAPTIVE_STEPS0 SMAA_MAX_SEARCH_STEPS
#define SMAA_ADAPTIVE_STEPS1 SMAA_MAX_SEARCH_STEPS
#define SMAA_ADAPTIVE_STEPS2 SMAA_MAX_SEARCH_STEPS
#else
#undef SMAA_MAX_SEARCH_STEPS
#define SMAA_MAX_SEARCH_STEPS SMAA_ADAPTIVE_STEPS2
#endif
""", 'tier block')

    out = replace_once(out, """// Edge Detection Pixel Shaders (First Pass)

/**
 * Luma Edge Detection""", """// Edge Detection Pixel Shaders (First Pass)

#define SMAA_EDGE_OUTPUT float3
float3 SMAAEncodeEdgeOutput(float2 edges, float finalDelta) {
    return float3(edges, finalDelta < SMAA_ADAPTIVE_T1? 0.0 : (finalDelta < SMAA_ADAPTIVE_T2? 0.5 : 1.0));
}

/**
 * Luma Edge Detection""", 'edge output')

    for name in ('SMAALumaEdgeDetectionPS', 'SMAALumaEdgePredicationDetectionPS', 'SMAAColorEdgeDetectionPS',
                 'SMAAColorEdgePredicationDetectionPS', 'SMAADepthEdgeDetectionPS'):
        out = replace_once(out, f'float2 {name}(', f'SMAA_EDGE_OUTPUT {name}(', name)

    # The four luma/color edge functions end with the local contrast adaptation; the depth function has no
    # finalDelta and always takes the top tier.
    lca = """    edges.xy *= step(finalDelta, SMAA_LOCAL_CONTRAST_ADAPTATION_FACTOR * delta.xy);

    return edges;
}"""
    if out.count(lca) != 4:
        raise SystemExit(f'luma/color returns: expected 4, found {out.count(lca)}')
    out = out.replace(lca, """    edges.xy *= step(finalDelta, SMAA_LOCAL_CONTRAST_ADAPTATION_FACTOR * delta.xy);

    return SMAAEncodeEdgeOutput(edges, finalDelta);
}""")
    out = replace_once(out, """    float2 edges = step(SMAA_DEPTH_THRESHOLD, delta);

    if (dot(edges, float2(1.0, 1.0)) == 0.0)
        discard;

    return edges;
}""", """    float2 edges = step(SMAA_DEPTH_THRESHOLD, delta);

    if (dot(edges, float2(1.0, 1.0)) == 0.0)
        discard;

    return SMAAEncodeEdgeOutput(edges, 1.0);
}""", 'depth return')
    if 'return edges;' in out:
        raise SystemExit('an edge function still returns float2')

    out = replace_once(out, """// Blending Weight Calculation Pixel Shader (Second Pass)

float4 SMAABlendingWeightCalculationPS(""", """// Blending Weight Calculation Pixel Shader (Second Pass)

// At the top tier the search keeps the original end (offset[2], interpolated from the VS), so an
// untrimmed search matches the original exactly; the shorter tiers end inside their last step and run
// exactly maxSearchSteps iterations.
#define SMAA_SEARCH_END(originalEnd, origin, sign, pixelSize) (maxSearchSteps == SMAA_MAX_SEARCH_STEPS? originalEnd : origin sign 2.0 * float(maxSearchSteps) * pixelSize)

float4 SMAABlendingWeightCalculationPS(""", 'search end')

    out = replace_once(out, """    float2 e = SMAASample(edgesTex, texcoord).rg;
""", """    // 0.5 is stored as 128/255 and still selects the middle tier.
    float3 edgesTier = SMAASample(edgesTex, texcoord).rgb;
    float2 e = edgesTier.rg;
    int maxSearchSteps = edgesTier.b < 0.25? SMAA_ADAPTIVE_STEPS0 : (edgesTier.b < 0.75? SMAA_ADAPTIVE_STEPS1 : SMAA_MAX_SEARCH_STEPS);
""", 'tier read')

    for call, end, axis, sign, metric in (
            ('SMAASearchXLeft', 'offset[2].x', 'texcoord.x', '-', 'SMAA_RT_METRICS.x'),
            ('SMAASearchXRight', 'offset[2].y', 'texcoord.x', '+', 'SMAA_RT_METRICS.x'),
            ('SMAASearchYUp', 'offset[2].z', 'texcoord.y', '-', 'SMAA_RT_METRICS.y'),
            ('SMAASearchYDown', 'offset[2].w', 'texcoord.y', '+', 'SMAA_RT_METRICS.y')):
        offsets = 'offset[0].xy' if call == 'SMAASearchXLeft' else 'offset[0].zw' if call == 'SMAASearchXRight' else \
            'offset[1].xy' if call == 'SMAASearchYUp' else 'offset[1].zw'
        old = f'{call}(SMAATexturePass2D(edgesTex), SMAATexturePass2D(searchTex), {offsets}, {end});'
        new = f'{call}(SMAATexturePass2D(edgesTex), SMAATexturePass2D(searchTex), {offsets}, SMAA_SEARCH_END({end}, {axis}, {sign}, {metric}));'
        out = replace_once(out, old, new, call)
    return out


def build_fx(src, sha):
    out = replace_once(src, ' *                               for ReShade 3.0+\n */',
                       ' *                               for ReShade 3.0+\n *\n' + ORIGIN.format(ext='.fx', sha=sha) + ' */', 'origin')

    out = replace_once(out, """#if !defined(SMAA_PRESET_LOW) && !defined(SMAA_PRESET_MEDIUM) && !defined(SMAA_PRESET_HIGH) && !defined(SMAA_PRESET_ULTRA)
#define SMAA_PRESET_CUSTOM // Do not use a quality preset by default
#endif
""", """// The Adaptive tiers exist only for the four fixed presets. Use the same SMAA_PRESET_* definition as SMAA.fx
// when comparing the two; without one this effect uses Ultra.
#if !defined(SMAA_PRESET_LOW) && !defined(SMAA_PRESET_MEDIUM) && !defined(SMAA_PRESET_HIGH) && !defined(SMAA_PRESET_ULTRA)
#define SMAA_PRESET_ULTRA
#endif

// 1: every tier searches the preset maximum, so the output must equal SMAA.fx (test configuration).
#ifndef ADAPTIVE_SMAA_TIERS_AT_PRESET_MAX
#define ADAPTIVE_SMAA_TIERS_AT_PRESET_MAX 0
#endif
""", 'preset default')

    custom_start = out.index('#ifdef SMAA_PRESET_CUSTOM\nuniform float EdgeDetectionThreshold')
    custom_end = out.index('#endif\n', out.index('uniform float PredicationStrength')) + len('#endif\n')
    out = out[:custom_start] + out[custom_end:].lstrip('\n')
    define_start = out.index('#ifdef SMAA_PRESET_CUSTOM\n\t#define SMAA_PREDICATION PredicationEnabled')
    define_end = out.index('#endif\n', define_start) + len('#endif\n')
    out = out[:define_start] + out[define_end:].lstrip('\n')
    if 'SMAA_PRESET_CUSTOM' in out:
        raise SystemExit('custom preset left')

    out = replace_once(out, """	ui_items = "Luminance edge detection\\0Color edge detection\\0Depth edge detection\\0";
	ui_label = "Edge Detection Type";
> = 1;""", """	ui_items = "Luminance edge detection\\0Color edge detection\\0Depth edge detection\\0";
	ui_label = "Edge Detection Type";
	ui_tooltip = "The tier thresholds were measured with luminance edge detection.";
> = 0;""", 'edge type')

    out = replace_once(out, """	ui_items = "None\\0View edges\\0View weights\\0";
	ui_label = "Debug Output";""", """	ui_items = "None\\0View edges\\0View weights\\0View search tiers\\0";
	ui_label = "Debug Output";
	ui_tooltip = "View search tiers: blue = shortest search, green = middle, red = top tier, black = no edge.";""", 'debug items')

    for name in ('depthTex', 'edgesTex', 'blendTex', 'areaTex', 'searchTex'):
        for pattern in (f'texture {name} <', f'Texture = {name};', f'RenderTarget = {name};'):
            if pattern in out:
                out = out.replace(pattern, pattern.replace(name, 'AdaptiveSMAA_' + name))
        if name in out.replace('AdaptiveSMAA_' + name, ''):
            raise SystemExit(f'{name} not fully renamed')

    out = replace_once(out, """texture AdaptiveSMAA_edgesTex < pooled = true; >
{
	Width = BUFFER_WIDTH;
	Height = BUFFER_HEIGHT;
	Format = RG8;
};""", """texture AdaptiveSMAA_edgesTex < pooled = true; >
{
	Width = BUFFER_WIDTH;
	Height = BUFFER_HEIGHT;
	Format = RGBA8; // .b holds the search tier
};""", 'edges format')

    out = replace_once(out, '#include "SMAA.fxh"', '#include "AdaptiveSMAA.fxh"', 'include')
    out = replace_once(out, 'float2 SMAAEdgeDetectionWrapPS(', 'SMAA_EDGE_OUTPUT SMAAEdgeDetectionWrapPS(', 'edge wrap')

    out = replace_once(out, """	if (DebugOutput == 1)
		return tex2D(edgesSampler, texcoord).rgb;
	if (DebugOutput == 2)
		return tex2D(blendSampler, texcoord).rgb;
""", """	if (DebugOutput == 1)
		return float3(tex2D(edgesSampler, texcoord).rg, 0.0);
	if (DebugOutput == 2)
		return tex2D(blendSampler, texcoord).rgb;
	if (DebugOutput == 3)
	{
		float3 e = tex2D(edgesSampler, texcoord).rgb;
		float3 tier = e.b < 0.25 ? float3(0.2, 0.4, 1.0) : (e.b < 0.75 ? float3(0.2, 1.0, 0.2) : float3(1.0, 0.3, 0.2));
		return (e.r > 0.0 || e.g > 0.0) ? tier : float3(0.0, 0.0, 0.0);
	}
""", 'debug view')

    out = replace_once(out, '\ntechnique SMAA\n', '\ntechnique AdaptiveSMAA\n', 'technique')
    return out


def main():
    root, out_dir = Path(sys.argv[1]), Path(sys.argv[2])
    sources = {}
    for rel, expected in SOURCE_SHA256.items():
        data = (root / rel).read_bytes()
        actual = hashlib.sha256(data).hexdigest()
        if actual != expected:
            raise SystemExit(f'{rel}: SHA-256 {actual} != {expected}')
        sources[rel] = data.decode('utf-8')
    out_dir.mkdir(parents=True, exist_ok=True)
    fxh = build_fxh(sources['Shaders/SweetFX/SMAA.fxh'], SOURCE_SHA256['Shaders/SweetFX/SMAA.fxh'])
    fx = build_fx(sources['Shaders/SweetFX/SMAA.fx'], SOURCE_SHA256['Shaders/SweetFX/SMAA.fx'])
    for name, text in (('AdaptiveSMAA.fxh', fxh), ('AdaptiveSMAA.fx', fx)):
        path = out_dir / name
        path.write_bytes(text.encode('utf-8'))
        print(f'{path} {len(text.encode("utf-8"))} {hashlib.sha256(text.encode("utf-8")).hexdigest()}')


if __name__ == '__main__':
    main()
